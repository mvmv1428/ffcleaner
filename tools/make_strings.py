out = Path(__file__).resolve().parents[1] / 'src' / 'FFCleaner.Desktop' / 'Strings'
out.mkdir(exist_ok=True)
for index, lang in enumerate(['es', 'en']):
    lines = ['<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
             '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">',
             f' <!-- Textos fijos de la interfaz ({lang}). Mismas claves en es.xaml y en.xaml; generado desde una sola tabla. -->']
    for key, pair in S.items():
        lines.append(f' <sys:String x:Key="S.{key}">{escape(pair[index])}</sys:String>')
    lines.append('</ResourceDictionary>')
    (out / f'{lang}.xaml').write_text('\n'.join(lines) + '\n', encoding='utf-8')
